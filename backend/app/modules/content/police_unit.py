"""Контент флагманского направления: «Общение с полицией».

Отдельный модуль, а не правка ``curriculum.json`` руками, по трём причинам:
- 25 уроков × (теория + 5 вопросов) — это ~1500 строк JSON, который
  невозможно поддерживать и в котором легко сломать запятую;
- одна функция ``police_lessons()`` держит структуру урока одинаковой, поэтому
  новый урок добавляется одной записью в списке ``LESSONS``;
- вопросы генерируются из компактного описания (варианты + индекс верного),
  так что индекс правильного ответа невозможно «съехать» от правки текста.

Запуск: ``python -m app.modules.content.police_unit`` перезапишет секцию
``police`` в ``app/content_packs/curriculum.json``.
"""

from __future__ import annotations

from typing import Any

# Каждый урок: (slug, заголовок, [(теория: title, definition, practical, chips, bear_line)],
#              [(вопрос: prompt, варианты, индекс верного, разбор)])


def _card(order: int, title: str, definition: str, practical: str,
          chips: list[str], bear_line: str) -> dict[str, Any]:
    return {
        "order": order,
        "title": title,
        "definition": definition,
        "practical": practical,
        "chips": chips,
        "bear_line": bear_line,
    }


def _question(order: int, prompt: str, options: list[str], correct: int,
              explanation: str, case_text: str | None = None) -> dict[str, Any]:
    return {
        "order": order,
        "kind": "case" if case_text else "choice",
        "prompt": prompt,
        "case_text": case_text,
        "options": options,
        "correct": correct,
        "explanation": explanation,
    }


def _lesson(slug: str, title: str, order: int, xp: int,
            cards: list[dict], questions: list[dict]) -> dict[str, Any]:
    return {
        "slug": slug,
        "title": title,
        "order": order,
        "xp_reward": xp,
        "cards": cards,
        "questions": questions,
    }



