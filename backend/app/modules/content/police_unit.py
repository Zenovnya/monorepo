def police_lessons() -> list[dict[str, Any]]:
    """Все 25 уроков юнита в порядке ``order``."""
    lessons: list[dict[str, Any]] = []
    for part in (
        _lessons_part_one,
        _lessons_part_two,
        _lessons_part_three,
        _lessons_part_four,
        _lessons_part_five,
        _lessons_part_six,
    ):
        lessons.extend(part())
    return sorted(lessons, key=lambda lesson: lesson["order"])


def police_unit() -> dict[str, Any]:
    """Полный объект юнита для ``curriculum.json``."""
    return {**POLICE_UNIT, "lessons": police_lessons()}


def _main() -> int:
    """Перезаписать секцию ``police`` в curriculum.json и отвалидировать её."""
    import json
    from pathlib import Path

    from app.modules.content.content_schemas import UnitIn

    curriculum_path = Path(__file__).resolve().parents[2] / "content_packs" / "curriculum.json"
    payload = json.loads(curriculum_path.read_text(encoding="utf-8"))

    unit = police_unit()
    validated = UnitIn.model_validate(unit)

    units = payload.get("units", [])
    replaced = False
    for index, existing in enumerate(units):
        if existing.get("code") == POLICE_UNIT["code"]:
            units[index] = unit
            replaced = True
            break
    if not replaced:
        units.append(unit)

    units.sort(key=lambda item: item.get("order", 0))
    payload["units"] = units
    curriculum_path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    total_questions = sum(len(lesson.questions) for lesson in validated.lessons)
    print(
        f"{'updated' if replaced else 'added'} unit "
        f"'{validated.code}': {len(validated.lessons)} lessons, "
        f"{total_questions} questions -> {curriculum_path}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
