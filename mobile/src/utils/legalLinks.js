/**
 * Парсер и рендерер ссылок на нормативные акты.
 *
 * Находит в тексте ссылки на статьи ("Ст. 158 УК РФ"), федеральные законы
 * ("№ 353-ФЗ") и постановления правительства ("ПП РФ №354"), возвращая
 * список сегментов — обычный текст и «правовая ссылка» с URL поискового
 * запроса в Консультант Плюс. Компонент {@link LegalText} использует эту
 * функцию для рендера кликабельных ссылок.
 *
 * URL для клика: consultant.ru/search/base/?q=<запрос> — открывает результаты
 * поиска по нормативным актам. Точный deep-link на конкретную статью
 * требует знания внутренних ID Консультант Плюс, что для 100+ кейсов не
 * масштабируется; поиск даёт стабильный универсальный опыт.
 */

// Regex ловит несколько форматов:
//  - "Ст. 158", "ст 158", "Статья 158", "статьи 158.1"
//  - "158-ФЗ", "№ 353-ФЗ", "ФЗ №158"
//  - "ПП РФ №354" / "постановление 354"
// После совпадения добавляем контекст (следующие 1-2 слова кодекса), чтобы
// поиск в Консультант Плюс был точнее: "Ст. 158 УК РФ" → ищем именно это.
const LEGAL_RE = new RegExp(
  [
    // Статьи (с необязательным упоминанием кодекса рядом)
    '(?:Ст\\.?|ст\\.?|Статья|статья|статьи|статей)\\s*\\d+(?:\\.\\d+)*(?:\\s+ч\\.?\\s*\\d+)?(?:\\s+(?:УК|ГК|КоАП|ТК|СК|ЖК|НК|ГПК|УПК|АПК)(?:\\s+РФ)?)?',
    // Отдельные федеральные законы
    '(?:№\\s*)?\\d{1,4}[- ]?ФЗ',
    // Постановления правительства
    '(?:ПП\\s+РФ|Постановление\\s+Правительства\\s+РФ)\\s*№?\\s*\\d+',
  ].join('|'),
  'g',
);

/** Собирает поисковый URL Консультант Плюс из подстроки-ссылки. */
export function buildConsultantUrl(refText) {
  const q = refText.trim().replace(/\s+/g, ' ');
  return `https://www.consultant.ru/search/?q=${encodeURIComponent(q)}`;
}

/**
 * Разбивает текст на сегменты: обычный текст и правовые ссылки.
 * @param {string} text
 * @returns {Array<{text: string, url?: string}>}
 */
export function splitLegalRefs(text) {
  if (!text) return [];
  const parts = [];
  let cursor = 0;
  let match;
  const re = new RegExp(LEGAL_RE.source, 'g');
  while ((match = re.exec(text)) !== null) {
    if (match.index > cursor) {
      parts.push({ text: text.slice(cursor, match.index) });
    }
    parts.push({ text: match[0], url: buildConsultantUrl(match[0]) });
    cursor = match.index + match[0].length;
  }
  if (cursor < text.length) parts.push({ text: text.slice(cursor) });
  return parts;
}
