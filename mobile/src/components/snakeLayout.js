/**
 * Геометрия карты уроков: чистая математика, без React и react-native.
 *
 * Зачем отдельный файл: раскладку тропы можно посчитать и проверить без
 * отрисовки. «Узлы налезли друг на друга» и «тропа вышла за экран» — это
 * арифметика, и её видно числом, а не только глазами на телефоне.
 *
 * Схема — S-образная кривая (техзадание §2): тропа идёт
 * «центр → вправо → центр → влево → центр», уроки сидят на ней
 * через равные промежутки.
 */

/** Диаметр медальона урока. */
export const NODE = 72;
/** Горизонтальный отступ: медальон не касается края полотна. */
export const PADDING_X = 30;
/**
 * Расстояние между центрами по вертикали.
 *
 * 104, а не 118: подписи под медальонами убраны (техзадание §2),
 * поэтому межд узлами нужен только визуальный отзор. При 118 тропа
 * из 5 узлов занимала бы 590px — слишком много для раскрытой карточки.
 */
export const STEP_Y = 104;
/** Насколько тропа уходит влево-вправо от центра (доля свободной ширины). */
export const AMPLITUDE = 0.3;
/** Верхний отступ: под tooltip-бабл над первым узлом. */
export const TOP_PAD = 108;

/**
 * Центры медальонов.
 *
 * Фаза синуса — π/2: для пяти узлов получается именно S-образная кривая
 * «центр → вправо → центр → влево → центр». Шаг π дал бы зигзаг, который
 * выглядит как шум, а не как путь.
 */
export function snakePoints(count, width) {
  if (!count || count < 1) return [];
  const inner = Math.max(width - PADDING_X * 2, NODE);
  const center = width / 2;
  return Array.from({ length: count }, (_, index) => ({
    x: center + Math.sin((index * Math.PI) / 2) * inner * AMPLITUDE,
    y: TOP_PAD + NODE / 2 + index * STEP_Y,
  }));
}

/** Высота полотна под `count` медальонов (с запасом снизу). */
export function pathHeight(count) {
  if (!count || count < 1) return 0;
  return TOP_PAD + NODE / 2 + (count - 1) * STEP_Y + NODE / 2 + 24;
}

/**
 * Индекс «следующего» урока — первый непройденный.
 *
 * `-1`, если пройдено всё: подсвечивать тогда нечего, и любой выбор выглядел
 * бы произвольным.
 */
export function nextLessonIndex(lessons) {
  if (!Array.isArray(lessons)) return -1;
  return lessons.findIndex((lesson) => !lesson.practised);
}
